import { existsSync, mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import type { BrowserWindow } from "electron";
import { dialog } from "electron";
import { afterAll, afterEach, describe, expect, it, vi } from "vitest";
import { frontProject, frontAssets } from "./helpers/front-project.js";
import { ProjectPdfService } from "../src/main/documents/pdf-service.js";
import type { ProjectDocumentView } from "../src/shared/project.js";

vi.mock("electron", () => ({
  app: { getPath: () => tmpdir() },
  BrowserWindow: class {},
  dialog: { showSaveDialog: vi.fn() },
}));

const scratch = mkdtempSync(path.join(tmpdir(), "librequadri-pdf-test-"));
afterEach(() => vi.resetAllMocks());

const project = {
  metadata: { title: "Quadro Q1", date: "2026-10-01", companyName: "Cliente", companyDescription: "",
    description: "", normCode: "CEI EN 60898", executor: "", notes: "" },
  lines: [{ lineType: "product", manufacturerCode: "A1", description: "Articolo", quantity: 1,
    unitListPriceE4: 120_000, lineTotalE4: 120_000 }],
  configuredItems: [], distinta: [],
} as unknown as ProjectDocumentView;

type WindowRecord = { options: Electron.BrowserWindowConstructorOptions; url: string; destroyed: boolean;
  openHandler?: (details: Electron.HandlerDetails) => { action: "deny" | "allow" };
  printOptions?: Electron.PrintToPDFOptions;
  navigationHandler?: (event: Electron.Event, url: string) => void };

function mockPdfWindows(pdf: Buffer) {
  const windows: WindowRecord[] = [];
  const factory = { create(options: Electron.BrowserWindowConstructorOptions): BrowserWindow {
    const record: WindowRecord = { options, url: "", destroyed: false };
    windows.push(record);
    return {
      webContents: { setWindowOpenHandler: (handler: typeof record.openHandler) => { record.openHandler = handler; },
        on: (name: string, handler: typeof record.navigationHandler) => {
          if (name === "will-navigate") record.navigationHandler = handler;
        },
        printToPDF: async (options: Electron.PrintToPDFOptions) => { record.printOptions = options; return pdf; } },
      loadURL: async (url: string) => { record.url = url; },
      on: () => undefined, show: () => undefined, destroy: () => { record.destroyed = true; },
    } as unknown as BrowserWindow;
  } };
  return { windows, service: new ProjectPdfService(() => undefined, factory) };
}

describe("main-owned PDF preview and save", () => {
  const pdf = Buffer.from("%PDF-1.7\nexact generated bytes");

  it.each(["preventivo", "distinta"] as const)("saves %s directly with current prices and the same generation as preview", async kind => {
    const { windows, service } = mockPdfWindows(pdf);
    const before = structuredClone(project);
    for (const showPrices of [false, true]) {
      const start = windows.length;
      const destination = path.join(scratch, `${kind}-${showPrices}.pdf`);
      vi.mocked(dialog.showSaveDialog).mockImplementationOnce(async options => {
        // Only the hidden generator exists, and it is already destroyed when native save opens.
        expect(windows).toHaveLength(start + 1);
        expect(windows[start]!.destroyed).toBe(true);
        expect(options).toMatchObject({ title: "Salva PDF", filters: [{ name: "PDF", extensions: ["pdf"] }] });
        expect(options.defaultPath).toContain(`${kind === "preventivo" ? "Preventivo" : "Distinta"} - Quadro Q1.pdf`);
        return { canceled: false, filePath: destination };
      });
      expect(await service.saveDocument(project, kind, showPrices)).toBe(true);
      expect(readFileSync(destination)).toEqual(pdf);
      const generator = windows[start]!;
      expect(generator.options.webPreferences).toMatchObject({ sandbox: true, contextIsolation: true,
        javascript: false, nodeIntegration: false });
      const html = decodeURIComponent(generator.url.split(",").slice(1).join(","));
      expect(html.includes("Prezzo unitario")).toBe(showPrices);
      expect(html.includes(kind === "preventivo" ? "TOTALE FINALE" : "Totale di listino")).toBe(showPrices);
      await service.preview(project, kind, showPrices);
      expect(windows[start + 1]!.url).toBe(generator.url);
      expect(windows[start + 1]!.printOptions).toEqual(generator.printOptions);
    }
    expect(project).toEqual(before);
  });

  it.each([
    { labels: false, dimensions: false }, { labels: true, dimensions: false },
    { labels: false, dimensions: true }, { labels: true, dimensions: true },
  ])("saves the front directly with %j without creating a viewer or preview token", async options => {
    const { windows, service } = mockPdfWindows(pdf);
    const before = structuredClone(frontProject);
    const destination = path.join(scratch, `direct-front-${options.labels}-${options.dimensions}.pdf`);
    vi.mocked(dialog.showSaveDialog).mockResolvedValueOnce({ canceled: false, filePath: destination });
    // Missing artwork exercises the visible label fallback as well as the option boundary.
    expect(await service.saveFront(frontProject, {}, options)).toBe(true);
    expect(windows).toHaveLength(1);
    expect(windows[0]!.destroyed).toBe(true);
    expect(readFileSync(destination)).toEqual(pdf);
    const html = decodeURIComponent(windows[0]!.url.split(",").slice(1).join(","));
    expect(html.includes(">C16</text>")).toBe(options.labels);
    expect(html.includes('data-dimension="width"')).toBe(options.dimensions);
    await service.previewFront(frontProject, {}, options);
    expect(windows[1]!.url).toBe(windows[0]!.url);
    expect(windows[1]!.printOptions).toEqual(windows[0]!.printOptions);
    expect(frontProject).toEqual(before);
  });

  it.each(["preventivo", "distinta", "fronte-quadro"] as const)("handles canceled direct %s save without writing or opening a viewer", async kind => {
    const { windows, service } = mockPdfWindows(pdf);
    const destination = path.join(scratch, `canceled-${kind}.pdf`);
    vi.mocked(dialog.showSaveDialog).mockResolvedValueOnce({ canceled: true, filePath: destination });
    expect(await (kind === "fronte-quadro" ? service.saveFront(frontProject, frontAssets, { labels: true, dimensions: false })
      : service.saveDocument(project, kind, true))).toBe(false);
    expect(existsSync(destination)).toBe(false);
    expect(windows).toHaveLength(1);
    expect(windows[0]!.destroyed).toBe(true);
  });

  it("keeps an existing preview/token usable when direct save generates new options", async () => {
    const { windows, service } = mockPdfWindows(pdf);
    const token = await service.preview(project, "preventivo", true);
    vi.mocked(dialog.showSaveDialog).mockResolvedValue({ canceled: true, filePath: "" });
    expect(await service.saveDocument(project, "distinta", false)).toBe(false);
    expect(windows).toHaveLength(3);
    expect(windows[1]!.destroyed).toBe(false);
    expect(await service.save(token)).toBe(false);
    expect(windows).toHaveLength(3);
  });

  it("rejects invalid generated bytes before native save and destroys the generator", async () => {
    const { windows, service } = mockPdfWindows(Buffer.from("not a PDF"));
    await expect(service.saveDocument(project, "preventivo", true)).rejects.toThrow("Generazione PDF");
    expect(windows).toHaveLength(1);
    expect(windows[0]!.destroyed).toBe(true);
    expect(dialog.showSaveDialog).not.toHaveBeenCalled();
  });

  it("keeps the hidden HTML generator sandboxed with JavaScript disabled", async () => {
    const { windows, service } = mockPdfWindows(pdf);
    await service.preview(project, "preventivo", true);
    const generator = windows[0]!;
    expect(generator.options).toMatchObject({ show: false });
    expect(generator.options.webPreferences).toMatchObject({ sandbox: true, contextIsolation: true,
      javascript: false, nodeIntegration: false });
    expect(generator.options.webPreferences).not.toHaveProperty("preload");
    expect(generator.openHandler?.({} as Electron.HandlerDetails)).toEqual({ action: "deny" });
    const generatorNavigation = { preventDefault: vi.fn() };
    generator.navigationHandler?.(generatorNavigation as unknown as Electron.Event, "https://example.com");
    expect(generatorNavigation.preventDefault).toHaveBeenCalledOnce();
    expect(generator.destroyed).toBe(true);
    expect(generator.printOptions).toMatchObject({ pageSize: "A4", displayHeaderFooter: true,
      margins: { top: .65, bottom: .7, left: .62, right: .62 } });
  });

  it("prints the complete front on one fitted A4 page and saves the same main-owned bytes", async () => {
    const { windows, service } = mockPdfWindows(pdf);
    const before = structuredClone(frontProject);
    const token = await service.previewFront(frontProject, frontAssets, { labels: true, dimensions: true });
    const html = decodeURIComponent(windows[0]!.url.split(",").slice(1).join(","));
    expect(html).toContain("Fronte Quadro");
    expect(html).toContain("Linea 1");
    expect(html).not.toMatch(/front-selection|front-hit|textarea/);
    expect(windows[0]!.printOptions).toMatchObject({ pageSize: "A4", preferCSSPageSize: true,
      displayHeaderFooter: false, margins: { top: 0, bottom: 0, left: 0, right: 0 } });
    expect(windows[0]!.options.webPreferences?.javascript).toBe(false);
    expect(windows[1]!.options.title).toMatch(/^Fronte Quadro - Q1/);
    const destination = path.join(scratch, "front.pdf");
    vi.mocked(dialog.showSaveDialog).mockResolvedValueOnce({ canceled: false, filePath: destination });
    expect(await service.save(token)).toBe(true);
    expect(readFileSync(destination)).toEqual(pdf);
    expect(frontProject).toEqual(before);
  });

  it("constrains the PDF viewer, saves its exact bytes, and treats cancel normally", async () => {
    const { windows, service } = mockPdfWindows(pdf);
    const token = await service.preview(project, "preventivo", true);
    expect(token).toMatch(/^[0-9a-f-]{36}$/);
    expect(windows).toHaveLength(2);
    const preview = windows[1]!;
    expect(preview.options.webPreferences).toMatchObject({ sandbox: true, contextIsolation: true,
      javascript: true, nodeIntegration: false });
    expect(preview.options.webPreferences).not.toHaveProperty("preload");
    expect(preview.openHandler?.({} as Electron.HandlerDetails)).toEqual({ action: "deny" });
    expect(preview.url).toBe(`data:application/pdf;base64,${pdf.toString("base64")}`);
    const allowedNavigation = { preventDefault: vi.fn() };
    preview.navigationHandler?.(allowedNavigation as unknown as Electron.Event, preview.url);
    expect(allowedNavigation.preventDefault).not.toHaveBeenCalled();
    const deniedNavigation = { preventDefault: vi.fn() };
    preview.navigationHandler?.(deniedNavigation as unknown as Electron.Event, "https://example.com");
    expect(deniedNavigation.preventDefault).toHaveBeenCalledOnce();
    const destination = path.join(scratch, "saved.pdf");
    vi.mocked(dialog.showSaveDialog).mockResolvedValueOnce({ canceled: false, filePath: destination });
    expect(await service.save(token)).toBe(true);
    expect(readFileSync(destination)).toEqual(pdf);
    vi.mocked(dialog.showSaveDialog).mockResolvedValueOnce({ canceled: true, filePath: "" });
    expect(await service.save(token)).toBe(false);
    expect(readFileSync(destination)).toEqual(pdf);
  });
});

afterAll(() => rmSync(scratch, { recursive: true, force: true }));
